#!/usr/bin/env node
/**
 * Copies the ACC file generator from the cloud repo (`fun`) into
 * src/acc-core/, so the laptop builds offline files with the exact code the
 * cloud uses. Never edit src/acc-core/ by hand: change it in `fun`, then run
 *
 *   node scripts/sync-acc-core.js [path-to-fun]     (default: ../fun)
 *
 * and commit the copy together with the refreshed golden fixture.
 * test/accCore.test.js fails if the copy and the fixture disagree.
 */
const fs = require("fs");
const path = require("path");

const fun = path.resolve(process.argv[2] || path.join(__dirname, "..", "..", "fun"));
const src = path.join(fun, "functions", "mall", "acc", "_core");
const models = path.join(fun, "functions", "shared", "models");
const out = path.join(__dirname, "..", "src", "acc-core");
const fixtures = path.join(__dirname, "..", "test", "fixtures", "acc");

if (!fs.existsSync(src)) {
  console.error(`[sync-acc-core] not found: ${src}`);
  process.exit(1);
}

fs.mkdirSync(path.join(out, "models"), { recursive: true });
fs.mkdirSync(fixtures, { recursive: true });

const header = (from) =>
  `// GENERATED by scripts/sync-acc-core.js from fun/${from}. Do not edit.\n`;

for (const f of ["AccDataBuilder.js", "calcDailyFile.js", "buildDailyFile.js"]) {
  const code = fs
    .readFileSync(path.join(src, f), "utf8")
    .replace(/\.\.\/\.\.\/\.\.\/shared\/models\//g, "./models/");
  fs.writeFileSync(path.join(out, f), header(`functions/mall/acc/_core/${f}`) + code);
}
for (const f of ["Transaction.js", "TransactionItem.js"]) {
  const code = fs.readFileSync(path.join(models, f), "utf8");
  fs.writeFileSync(path.join(out, "models", f), header(`functions/shared/models/${f}`) + code);
}
for (const f of fs.readdirSync(path.join(src, "__tests__", "fixtures"))) {
  fs.copyFileSync(path.join(src, "__tests__", "fixtures", f), path.join(fixtures, f));
}
console.log(`[sync-acc-core] copied from ${fun}`);
